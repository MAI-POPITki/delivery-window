"""Дополнительный 2025 год М1: пересчёт из сырых прогнозов; пробелы в проверке М2/М3."""
from pathlib import Path
import numpy as np
import pandas as pd

ROOT=Path(__file__).resolve().parents[1]


def main():
    d=pd.read_csv(ROOT/'reports/flood_m1_quantile_predictions.csv.gz',parse_dates=['issue','target_date'])
    d=d[d.issue.dt.year.eq(2025)&d.issue.dt.month.between(4,7)&d.lead.isin([1,3,7])]
    lines=['# Проверка качества паводковых модулей','',
        'М1: дополнительный 2025 год, апрель–июль. Пересчёт по сырым прогнозам, '
        'без настройки параметров по этому году. Позднее полученный архив; это не '
        'сохранённые оперативные выпуски. Проверяется уровень, не затопление дороги.','',
        '| Пост | Горизонт | N | MAE М1, см | Сохранить уровень, см | Покрытие | Ширина, см |',
        '| --- | ---: | ---: | ---: | ---: | ---: | ---: |']
    for (pid,h),g in d.groupby(['pid','lead']):
        assert ((g.target_date-g.issue).dt.days==h).all()
        mae=np.mean(np.abs(g.target-g.m1));base=np.mean(np.abs(g.target-g.persistence))
        coverage=np.mean((g.target>=g.lower)&(g.target<=g.upper))
        lines.append(f'| {pid} | {h} | {len(g)} | {mae:.1f} | {base:.1f} | {coverage:.0%} | {(g.upper-g.lower).mean():.1f} |')
    lines+=['','В 2025 году оба поста точнее сохранения уровня на этих горизонтах. '
        'Диапазоны широки после экстремального калибровочного 2024 года. Один '
        'дополнительный год не подтверждает устойчивость к следующему экстремуму. '
        'Полные результаты 2019–2025: flood_m1_quantile.md; провал покрытия '
        'весны 2024 года там сохранён.','',
        '## М2: независимый внешний тест и локальные ограничения','',
        'Ручная разметка Sen1Floods11 подключена: [flood_m2_benchmark.md](flood_m2_benchmark.md). '
        'Она проверяет выделение воды на внешних L1C-снимках. Точность контура '
        'затопления наших российских L2A-сцен пока отдельно не подтверждена.','',
        'Реальные маски воспроизводятся, но IoU с SCL — согласие двух методов на '
        'одном снимке, а не независимая точность затопления. Найден независимый источник: '
        '[International Charter, активация 871, карты Роскомоса]'
        '(https://disasterscharter.org/activations/flood-in-russian-federation-activation-871-). '
        'Страница содержит продукты Орска за 8 апреля и опубликованные 23 апреля карты. '
        'Это не совпадающая по времени пиксельная разметка нашего снимка Орска 11 апреля. '
        'F1/IoU затопления без геопривязанной разметки и учёта даты не рассчитываются. '
        'Нужны независимые контуры воды/суши с временем наблюдения и маской неизвестного; '
        'проверять следует отдельно постоянную воду и новую воду, исключая облака.','',
        '## М3: проверена оптимизация, не фактическая экономия','',
        'План сохраняет объём, не превышает мощности, требует подтверждения каждого '
        'дня рейса и полного прогноза. Сравнивается с равномерным планом при тех же '
        'ограничениях. Нижний/средний/верхний варианты — анализ чувствительности, '
        'не вероятность успеха рейса. Для проверки практической пользы нужны реальные '
        'заказы, тарифы, допуски и фактические доставки; такие данные не подставляются.']
    (ROOT/'reports/flood_accuracy.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')


if __name__=='__main__':main()
