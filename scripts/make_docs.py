def _crop_shots():
    """Снимки дашборда без левой панели (docs/tutorial/img, снимает scripts/tutorial_screenshots.py)."""
    from PIL import Image
    out = []
    for name, cap in (("01_map", "Карта путей: вероятность, что путь открыт через N дней"),
                      ("13b_flood_orsk", "Паводки: пример — Орск, апрель 2024")):
        src = ROOT / "docs" / "tutorial" / "img" / f"{name}.png"
        if not src.exists():
            continue
        im = Image.open(src)
        dst = BUILD / f"{name}_crop.png"
        im.crop((360, 90, im.width - 60, min(im.height, 760))).save(dst)
        out.append((dst, cap))
    return out


