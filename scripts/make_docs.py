def new_doc():
    doc = Document()
    sec = doc.sections[0]
    sec.page_width, sec.page_height = Cm(21), Cm(29.7)
    sec.left_margin = sec.right_margin = Cm(2)
    sec.top_margin = sec.bottom_margin = Cm(1.7)
    st = doc.styles["Normal"]
    st.font.name = "Arial"
    st.element.rPr.rFonts.set(qn("w:eastAsia"), "Arial")
    st.font.size = Pt(10.5)
    st.paragraph_format.space_after = Pt(4)
    st.paragraph_format.line_spacing = 1.12
    for name, size, before in (("Title", 26, 0), ("Heading 1", 15, 14), ("Heading 2", 12, 10)):
        s = doc.styles[name]
        s.font.name = "Arial"
        s.element.rPr.rFonts.set(qn("w:eastAsia"), "Arial")
        s.font.size = Pt(size)
        s.font.bold = True
        s.font.color.rgb = ACCENT
        s.paragraph_format.space_before = Pt(before)
        s.paragraph_format.space_after = Pt(6)
        s.paragraph_format.keep_with_next = True
    fp = sec.footer.paragraphs[0]
    fp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = fp.add_run()
    for tag, txt in (("begin", None), (None, "PAGE"), ("end", None)):
        if tag:
            e = OxmlElement("w:fldChar"); e.set(qn("w:fldCharType"), tag)
        else:
            e = OxmlElement("w:instrText"); e.set(qn("xml:space"), "preserve"); e.text = txt
        r._r.append(e)
    r.font.size = Pt(8)
    return doc


def _shade(cell, color):
    pr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement("w:shd"); sh.set(qn("w:val"), "clear"); sh.set(qn("w:color"), "auto"); sh.set(qn("w:fill"), color)
    pr.append(sh)


def _runs(p, text, size=None):
    parts = text.split("**")
    for i, part in enumerate(parts):
        if part:
            r = p.add_run(part)
            r.bold = i % 2 == 1
            if size:
                r.font.size = Pt(size)
    return p


class Writer:
    def __init__(self, doc):
        self.doc = doc

    def p(self, text, italic=False, size=None, color=None, align=None):
        p = _runs(self.doc.add_paragraph(), text, size)
        for r in p.runs:
            r.italic = italic or r.italic
            if color:
                r.font.color.rgb = color
        if align:
            p.alignment = align
        return p

    def h1(self, t):
        self.doc.add_heading(t, level=1)

    def h2(self, t):
        self.doc.add_heading(t, level=2)

    def bullets(self, items, size=None):
        for it in items:
            p = _runs(self.doc.add_paragraph(style="List Bullet"), it, size)
            p.paragraph_format.space_after = Pt(2)

    def numbered(self, items):
        for i, it in enumerate(items, 1):
            p = _runs(self.doc.add_paragraph(), f"{i}. {it}")
            p.paragraph_format.left_indent = Cm(0.7)
            p.paragraph_format.first_line_indent = Cm(-0.5)
            p.paragraph_format.space_after = Pt(2)

    def table(self, header, rows, widths, size=8.8, head_fill="D9E5F1"):
        t = self.doc.add_table(rows=1, cols=len(header))
        t.style = "Table Grid"
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        t.autofit = False
        lay = OxmlElement("w:tblLayout"); lay.set(qn("w:type"), "fixed"); t._tbl.tblPr.append(lay)
        for i, h in enumerate(header):
            c = t.rows[0].cells[i]; _shade(c, head_fill); c.paragraphs[0].text = ""
            r = c.paragraphs[0].add_run(h); r.bold = True; r.font.size = Pt(size)
        for row in rows:
            cells = t.add_row().cells
            for i, v in enumerate(row):
                cells[i].paragraphs[0].text = ""
                _runs(cells[i].paragraphs[0], str(v), size)
        for i, w in enumerate(widths):
            t.columns[i].width = Cm(w)
            for row in t.rows:
                row.cells[i].width = Cm(w)
        self.doc.add_paragraph().paragraph_format.space_after = Pt(1)
        return t

    def box(self, title, lines, fill="EAF2FB", size=None):
        t = self.doc.add_table(rows=1, cols=1)
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        c = t.rows[0].cells[0]; _shade(c, fill)
        if title:
            r = c.paragraphs[0].add_run(title); r.bold = True; r.font.color.rgb = ACCENT
            if size:
                r.font.size = Pt(size + 0.5)
        first = not title
        for ln in lines:
            q = c.paragraphs[0] if first else c.add_paragraph()
            first = False
            _runs(q, ln, size); q.paragraph_format.space_after = Pt(2)
        self.doc.add_paragraph().paragraph_format.space_after = Pt(1)

    def figure(self, path, caption, width=17):
        if not Path(path).exists():
            return
        self.doc.add_picture(str(path), width=Cm(width))
        self.doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
        self.p(caption, italic=True, size=8.5, color=GREY, align=WD_ALIGN_PARAGRAPH.CENTER)

    def page_break(self):
        self.doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)

    def kpis(self, items, fill="1F4E79"):
        """Ряд крупных цифр: [(число, подпись), ...]."""
        t = self.doc.add_table(rows=2, cols=len(items))
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        for i, (num, cap) in enumerate(items):
            for rr in (0, 1):
                _shade(t.rows[rr].cells[i], fill)
            r = t.rows[0].cells[i].paragraphs[0].add_run(num); r.bold = True; r.font.size = Pt(19)
            r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
            t.rows[0].cells[i].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
            r = t.rows[1].cells[i].paragraphs[0].add_run(cap); r.font.size = Pt(8.3)
            r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
            t.rows[1].cells[i].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        self.doc.add_paragraph().paragraph_format.space_after = Pt(1)


