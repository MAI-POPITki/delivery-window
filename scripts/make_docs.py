def _hyperlink(paragraph, url, text, size=9, color="1F4E79", bold=True):
    """Кликабельная ссылка в docx (LibreOffice переносит её в PDF)."""
    part = paragraph.part
    r_id = part.relate_to(url, "http://schemas.openxmlformats.org/officeDocument/2006/relationships/hyperlink", is_external=True)
    h = OxmlElement("w:hyperlink"); h.set(qn("r:id"), r_id)
    r = OxmlElement("w:r"); rpr = OxmlElement("w:rPr")
    for tag, val in (("w:color", color), ("w:sz", str(int(size * 2)))):
        el = OxmlElement(tag); el.set(qn("w:val"), val); rpr.append(el)
    u = OxmlElement("w:u"); u.set(qn("w:val"), "single"); rpr.append(u)
    if bold:
        rpr.append(OxmlElement("w:b"))
    r.append(rpr)
    tx = OxmlElement("w:t"); tx.text = text; tx.set(qn("xml:space"), "preserve"); r.append(tx)
    h.append(r); paragraph._p.append(h)


def _links_banner(doc, items, fill="FFF2CC", border_title="Продукт — откройте и попробуйте"):
    """Заметный блок со ссылками: [(подпись, url, пояснение), ...]."""
    tb = doc.add_table(rows=1 + len(items), cols=2)
    tb.alignment = WD_TABLE_ALIGNMENT.CENTER
    tb.autofit = False
    head = tb.rows[0].cells[0].merge(tb.rows[0].cells[1])
    _shade(head, "C00000")
    r = head.paragraphs[0].add_run("▶  " + border_title); r.bold = True; r.font.size = Pt(11)
    r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
    for i, (label, url, note) in enumerate(items, 1):
        a, b = tb.rows[i].cells
        _shade(a, fill); _shade(b, fill)
        ra = a.paragraphs[0].add_run(label); ra.bold = True; ra.font.size = Pt(9.5)
        _hyperlink(b.paragraphs[0], url, url, size=10)
        if note:
            rn = b.paragraphs[0].add_run("   " + note); rn.font.size = Pt(8); rn.font.color.rgb = GREY
    lay = OxmlElement("w:tblLayout"); lay.set(qn("w:type"), "fixed"); tb._tbl.tblPr.append(lay)
    tb.columns[0].width = Cm(4.6); tb.columns[1].width = Cm(13.4)
    for row in tb.rows:
        row.cells[0].width = Cm(4.6); row.cells[1].width = Cm(13.4)
    doc.add_paragraph().paragraph_format.space_after = Pt(1)


