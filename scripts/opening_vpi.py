"""
Сколько стоит идеальный прогноз ОТКРЫТИЯ зимника (верхняя граница пользы любого прогноза открытия).

    python scripts/opening_vpi.py      # → reports/opening_vpi.md, .csv

Логика. Перевозчик заранее назначает дату выхода техники P по какому-то правилу. Если путь открылся позже
(P < факт), техника простаивает; если раньше (P > факт), теряются дни работы — при плотном плане эти тонны
уходят дорогим каналом. При идеальном знании P = факт, потерь нет. Значит, польза идеального прогноза по
сравнению с правилом = потери этого правила.

Ошибки правил — по реальным официальным датам открытия (data/external/road_events.csv, 2018–2026,
расчёт scripts/official_dates_test.py, прогноз на 1 и 15 ноября, 1 декабря; только прошлые данные).
Цена дня ошибки — из реальных тарифов (tariffs.csv): надбавка авиации к зимнику до тех же сёл
(Якутск — Батагай: 157 − 95 = 62 тыс. ₽/т; по 6 направлениям 50–94 тыс. ₽/т). Цена простоя техники
в открытых источниках не найдена — даётся в машино-сутках.

Пример масштаба (допущение): колонна из 10 машин по 20 т, рейс Якутск — Батагай около 10 суток →
20 т/сут на колонну. Потерянный день при плотном плане = 20 т через авиацию = 20 × 62 тыс. ₽.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import numpy as np
import pandas as pd

from okno.report import md_table

AIR_PREMIUM = 62000.0     # ₽/т: авиа 157 000 − зимник 95 000 (Якутск — Батагай), tariffs.csv
COLUMN_T_PER_DAY = 20.0   # допущение: 10 машин × 20 т / рейс 10 сут


def main():
    df = pd.read_csv(ROOT / "reports" / "official_dates.csv")
    df = df[df.kind == "open"].copy()
    # прогноз М1 со сдвигом по той же дороге — только по прошлым сезонам
    out = []
    for r in df.itertuples():
        p = df[(df.road == r.road) & (df.issue == r.issue) & (df.hydro_year < r.hydro_year)]
        out.append(r.m1 + (p.actual - p.m1).mean() if len(p) else np.nan)
    df["m1_road"] = out
    rules = {"last_year": "как в прошлом году", "road_cal": "календарь дороги",
             "m1_road": "М1 + сдвиг дороги", "announced": "объявленный план"}
    rows = []
    for col, name in rules.items():
        d = df[df[col].notna()]
        if len(d) < 5:
            continue
        err = d[col] - d.actual          # > 0: техника вышла позже открытия (потерянные дни)
        late, early = err.clip(lower=0), (-err).clip(lower=0)
        rows.append({"правило даты выхода техники": name, "прогнозов": len(d), "дорог": d.road.nunique(),
                     "сезонов": d.hydro_year.nunique(),
                     "потеряно дней работы (среднее)": round(late.mean(), 1),
                     "дней простоя (среднее)": round(early.mean(), 1),
                     "всего дней ошибки": round(err.abs().mean(), 1),
                     "цена потерянных дней на колонну, тыс. ₽": round(late.mean() * COLUMN_T_PER_DAY * AIR_PREMIUM / 1e3)})
    res = pd.DataFrame(rows)
    res.to_csv(ROOT / "reports" / "opening_vpi.csv", index=False)
    lines = ["# Идеальный прогноз открытия: сколько он мог бы стоить", "",
             "Польза идеального прогноза по сравнению с правилом = потери этого правила (при идеальном знании "
             "техника выходит ровно в день открытия). Ошибки — по реальным официальным датам открытия 2018–2026. "
             "«Потеряно дней работы» — техника вышла позже открытия; «простой» — вышла раньше.", "",
             md_table(res), "",
             f"Цена потерянного дня — если план плотный и недовезённое уходит авиацией: {COLUMN_T_PER_DAY:.0f} т/сут "
             f"на колонну × надбавка авиации {AIR_PREMIUM/1e3:.0f} тыс. ₽/т (Якутск — Батагай, tariffs.csv). "
             "Колонна — допущение (10 машин по 20 т, рейс ~10 сут). Цена простоя не найдена в открытых источниках.", "",
             "**Как читать.** Это верхняя граница: ни один прогноз не даст больше, чем потери лучшего простого правила. "
             "Если план не плотный (окна хватает с запасом), потерянные дни ничего не стоят — техника довезёт позже.", ""]
    (ROOT / "reports" / "opening_vpi.md").write_text("\n".join(lines), encoding="utf-8")
    print(res.to_string(index=False))


if __name__ == "__main__":
    main()
